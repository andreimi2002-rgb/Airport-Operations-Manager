// Generates js/colors.js: the colours and abbreviation of every team of the five leagues (ESPN team lists),
// for the emblems drawn without the official logo (the Microsoft Store app). Run: node tools/build-colors.mjs
import { writeFileSync } from 'node:fs';

const PATHS = { NBA: 'basketball/nba', NHL: 'hockey/nhl', NFL: 'football/nfl', MLB: 'baseball/mlb', MLS: 'soccer/usa.1' };
const norm = s => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]/g, '');
const out = {};
for (const [l, p] of Object.entries(PATHS)) {
  const j = await (await fetch(`https://site.api.espn.com/apis/site/v2/sports/${p}/teams?limit=100`)).json();
  const teams = j.sports?.[0]?.leagues?.[0]?.teams?.map(x => x.team) || [];
  for (const t of teams) {
    if (!t.color) continue;
    out[norm(t.displayName)] = [`#${t.color}`, t.alternateColor ? `#${t.alternateColor}` : '', t.abbreviation || ''];
  }
  console.log(l, teams.length);
}
const body = Object.entries(out).sort().map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
writeFileSync('js/colors.js', `// GENERATED by tools/build-colors.mjs: colour, second colour and abbreviation of every team, by its name
// (lower case, letters and digits only). Used for the emblems drawn without the official logo.
export const COLORS = {\n${body}\n};\n`);
console.log(Object.keys(out).length, 'teams');
